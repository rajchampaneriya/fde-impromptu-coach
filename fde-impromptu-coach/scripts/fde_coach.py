def cmd_doctor(args) -> int:
    from fdecoach import app, gcal, macos, questions, scheduler, youtube
    from fdecoach.state import Runtime
    ctx = _ctx(args)
    cfg, paths = ctx.cfg, ctx.paths
    problems = []

    def line(good: bool, label: str, detail: str = "") -> None:
        if not good:
            problems.append(label)
        print(f"[{'ok' if good else '!!'}] {label}{': ' + detail if detail else ''}")

    line(sys.version_info >= (3, 9), "Python", f"{sys.version.split()[0]} ({sys.executable})")
    for mod in ("pptx", "lxml", "googleapiclient", "google_auth_oauthlib"):
        try:
            __import__(mod)
            line(True, f"Python module {mod}")
        except ImportError:
            line(False, f"Python module {mod}", "missing - re-run install.sh")
    claude = questions.resolve_claude(cfg)
    if claude:
        try:
            ver = subprocess.run([claude, "--version"], capture_output=True, text=True, timeout=30).stdout.strip()
        except Exception as exc:  # noqa: BLE001
            ver = f"not runnable ({exc})"
        line(True, "Claude Code CLI", f"{claude} {ver}")
    else:
        line(False, "Claude Code CLI", "not found; set claude_path (the built-in bank still works)")
    line(macos.is_macos() or macos.dry_run(), "macOS", os.uname().sysname)
    line(macos.app_exists(cfg.get("presentation_app", "Microsoft PowerPoint")), "Microsoft PowerPoint installed")
    line(macos.app_exists("QuickTime Player"), "QuickTime Player installed")
    from fdecoach import audio
    line(audio.has_ffmpeg(), "ffmpeg (pronunciation video)",
         "found" if audio.has_ffmpeg() else "not found - pronunciation videos are skipped, audio is kept "
         "(brew install ffmpeg)")
    want_device = str(cfg.get("pronunciation", {}).get("audio_device", ""))
    devices = audio.avfoundation_audio_devices() if audio.has_ffmpeg() else []
    resolved = audio.resolve_audio_device(want_device) if devices else None
    line(bool(resolved is not None or not devices), "Pronunciation audio input",
         f"{devices[resolved][1] if resolved is not None and devices else want_device or 'first available'}"
         if devices else "dry-run or no ffmpeg")
    if not macos.dry_run() and macos.is_macos():
        ok_audio = macos.quicktime_audio_check()
        line(ok_audio, "QuickTime audio recording",
             "works" if ok_audio else "blocked - approve the microphone prompt (doctor --warmup)")
    else:
        line(True, "QuickTime audio recording", "dry-run")
    cam, mic = macos.has_camera(), macos.has_microphone()
    if cfg.get("recording", {}).get("mode") == "none":
        line(True, "Camera & microphone", "not needed (recording.mode=none: deck show only, no video)")
    else:
        line(cam and mic, "Camera & microphone",
             "found" if cam and mic else
             "not found - run sessions on a Mac with a camera, make camera-less practice the default "
             "(config --set recording.mode=none), or practise and mark the day: fde-coach complete --no-video")
    try:
        from fdecoach import library
        built, mine = len(library.builtin()), len(library.user_passages(paths))
        line(built > 0, "Passage library (public-domain books)", f"{built} built-in + {mine} imported")
    except Exception as exc:  # noqa: BLE001
        line(False, "Passage library (public-domain books)", f"unreadable: {exc}")
    rec = paths.recordings_dir(cfg, create=False)
    if rec.exists():
        free = shutil.disk_usage(str(rec)).free / 1e9
        line(os.access(str(rec), os.W_OK) and free > 2, "Recordings folder", f"{rec} ({free:.0f} GB free)")
    else:
        line(False, "Recordings folder", f"{rec} does not exist yet (created on first session)")
    for label, loaded in scheduler.status().items():
        line(loaded, f"launchd agent {label}", "loaded" if loaded else "not loaded - run: fde-coach install-agents")
        # A loaded agent can still fail on every tick (e.g. macOS TCC blocks
        # launchd from reading the script); surface the last logged error.
        err = paths.logs / f"{label.split('.')[-1]}.err.log"
        if err.exists() and time.time() - err.stat().st_mtime < 86400:
            # agent stderr also carries INFO lines; only real errors matter
            errors = [l for l in err.read_text(encoding="utf-8", errors="replace").splitlines()
                      if ("ERROR" in l or "Traceback" in l or "Errno" in l)]
            if errors:
                msg = errors[-1]
                line(False, f"agent {label} error log", msg[:120] + ("…" if len(msg) > 120 else ""))
    if cfg.get("youtube", {}).get("enabled", True):
        line(paths.client_secret.exists(), "YouTube OAuth client file", str(paths.client_secret))
        configured = youtube.is_configured(paths)
        line(configured, "YouTube authorized", "yes" if configured else "run: fde-coach youtube-auth")
    gc = cfg.get("google_calendar", {})
    if gc.get("enabled", True):
        connected = gcal.is_configured(paths)
        line(connected, "Google Calendar missed-practice alerts",
             f"on (event {gc.get('event_time')}, alerts {', '.join(gc.get('popup_times') or [])})" if connected
             else "run: fde-coach calendar-auth")
    rt = Runtime(paths)
    if rt.data.get("warmup_results"):
        print(f"     background permission check ({rt.data.get('warmup_at')}): " + "; ".join(rt.data["warmup_results"]))
    if args.warmup:
        print("Permission warm-up from this terminal (click OK/Allow on every macOS prompt):")
        for r in app.run_warmup(ctx):
            print("   " + r)
        app.update_runtime(ctx, lambda r: r.data.update(warmup_pending=True))
        scheduler.kickstart(scheduler.REMIND_LABEL)
        print("Also triggered the background agent so macOS asks for its own permissions now - approve those too.")
    log_file = paths.logs / "fde_coach.log"
    if log_file.exists():
        tail = log_file.read_text(encoding="utf-8", errors="ignore").splitlines()[-400:]
        errors = [ln for ln in tail if " ERROR " in ln or " WARNING " in ln]
        if errors:
            print("Recent warnings/errors:")
            for ln in errors[-8:]:
                print("   " + ln[:220])
    print("All good." if not problems else f"{len(problems)} item(s) need attention.")
    return 0 if not problems else 1


