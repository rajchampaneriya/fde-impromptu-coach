def _ctx(args):
    from fdecoach.app import Ctx
    return Ctx(verbose=getattr(args, "verbose", False))


def _print(obj) -> None:
    print(json.dumps(obj, indent=2, ensure_ascii=False))


def _sh(value: str) -> str:
    return "'" + value.replace("'", "'\"'\"'") + "'"


def _chmod_x(path: Path) -> None:
    path.chmod(path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)


# --------------------------------------------------------------------------- commands

def cmd_setup(args) -> int:
    from fdecoach import questions, scheduler
    from fdecoach.state import Runtime
    ctx = _ctx(args)
    paths, cfg = ctx.paths, ctx.cfg
    claude = questions.resolve_claude(cfg)
    if claude and not cfg.get("claude_path"):
        cfg["claude_path"] = claude
    if args.time:
        parse_hhmm(args.time)
        cfg["daily_time"] = args.time
    save_config(paths, cfg)

    paths.bin_dir.mkdir(parents=True, exist_ok=True)
    wrapper = paths.bin_dir / "fde-coach"
    wrapper.write_text(
        "#!/bin/bash\n"
        f"# {APP_NAME} launcher (generated by setup)\n"
        f"export FDE_COACH_HOME={_sh(str(paths.root))}\n"
        f"exec {_sh(sys.executable)} {_sh(str(ENTRY_SCRIPT))} \"$@\"\n", encoding="utf-8")
    _chmod_x(wrapper)
    paths.start_command.write_text(
        "#!/bin/bash\n"
        f"# Double-click to record today's {APP_NAME} session.\n"
        f"{_sh(str(wrapper))} session\n"
        "echo\n"
        "echo \"Done. You can close this window.\"\n", encoding="utf-8")
    _chmod_x(paths.start_command)
    paths.video_command.write_text(
        "#!/bin/bash\n"
        "# Double-click to record today's Software Factory video (up to three takes, then publish).\n"
        f"{_sh(str(wrapper))} factory take\n"
        "echo\n"
        "echo \"Done. You can close this window.\"\n", encoding="utf-8")
    _chmod_x(paths.video_command)

    rt = Runtime(paths)
    rt.data["warmup_pending"] = not args.no_warmup
    rt.save()
    print(f"{APP_NAME} {__version__}")
    print(f"  data folder   : {paths.root}")
    print(f"  recordings    : {paths.recordings_dir(cfg, create=False)}")
    print(f"  claude CLI    : {claude or 'NOT FOUND - questions will come from the built-in bank'}")
    print(f"  launcher      : {wrapper}")
    print(f"  double-click  : {paths.start_command}")
    print(f"  video series  : {paths.video_command}")
    if not args.no_agents:
        # Agent reinstall is a fresh start: clear old error output so doctor
        # does not keep reporting errors from a previous install.
        for err_log in paths.logs.glob("*.err.log"):
            err_log.write_text("", encoding="utf-8")
        for line in scheduler.install(cfg, paths):
            print(f"  launchd       : {line}")
        print(f"  schedule      : daily at {cfg['daily_time']}, reminder checks every 15 minutes")
    return 0


