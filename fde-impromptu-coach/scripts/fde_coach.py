def _coerce(value: str):
    try:
        return json.loads(value)
    except ValueError:
        return value


def cmd_config(args) -> int:
    from fdecoach import scheduler
    _ctx(args)
    paths = Paths()
    user = json.loads(paths.config.read_text(encoding="utf-8")) if paths.config.exists() else {}
    if args.set:
        reinstall = False
        for item in args.set:
            key, sep, raw = item.partition("=")
            if not key or not sep:
                print(f"bad --set {item!r}; use key=value (dotted keys for nested values, JSON for lists/bools)")
                return 2
            value = _coerce(raw)
            if key == "daily_time" or key.endswith(".daily_time"):
                parse_hhmm(str(value))
                reinstall = True
            node = user
            parts = key.split(".")
            for part in parts[:-1]:
                node = node.setdefault(part, {})
            node[parts[-1]] = value
        save_config(paths, user)
        print("Saved.")
        if reinstall:
            for line in scheduler.install(load_config(paths), paths):
                print(line)
    _print(load_config(paths))
    return 0


def cmd_level(args) -> int:
    from fdecoach import app
    from fdecoach.state import level_for, today
    ctx = _ctx(args)

    def change(rt) -> None:
        cur = 0 if args.reset else int(rt.data.get("level_adjust", 0)) + (1 if args.up else -1 if args.down else 0)
        rt.data["level_adjust"] = max(-4, min(4, cur))

    if args.up or args.down or args.reset:
        app.update_runtime(ctx, change)
    lvl = level_for(ctx.history(), ctx.cfg, ctx.runtime(), today())
    print(f"Level for the next new deck: {lvl} of 5 (manual adjustment {int(ctx.runtime().data.get('level_adjust', 0)):+d}). "
          "An existing deck keeps its level unless you run: fde-coach generate --replace")
    return 0


def cmd_pronounce(args) -> int:
    from fdecoach import app, pronounce_session
    ctx = _ctx(args)
    if args.pron_command == "session":
        if args.detach:
            app.spawn_detached(["pronounce", "session"] + (["--force"] if args.force else []))
            print("Pronunciation session started in the background: QuickTime audio + slide show "
                  "(about 5 minutes). Check progress with: fde-coach pronounce status")
            return 0
        res = pronounce_session.run_session(ctx, force=args.force)
        _print(res)
        return 0 if res.get("ok") else 1
    if args.pron_command == "daily":
        _print(pronounce_session.daily(ctx))
        return 0
    if args.pron_command == "generate":
        session, created = pronounce_session.ensure_today(ctx, replace=args.replace)
        _print({"date": session["date"], "day_number": session["day_number"], "source": session["source"],
                "created": created, "deck": session["deck_path"],
                "words": session["words"], "notes": session.get("notes", []),
                "paragraph": "hidden until you record (fde-coach pronounce history)"})
        return 0
    if args.pron_command == "status":
        st = pronounce_session.status(ctx)
        if args.json:
            _print(st)
            return 0
        s = st["streak"]
        print(f"Pronunciation streak: {s['current']} day(s)  |  best {s['best']}  |  "
              f"total {s['total']}  |  due words: {', '.join(st['due_words']) or '-'}")
        t = st["today"]
        if not t:
            print(f"Today ({st['date'] if 'date' in st else ''}): no deck yet (built at the pronunciation daily run)")
        else:
            state = "RECORDED" if t["recorded"] else "NOT RECORDED YET"
            print(f"Today: Day {t['day_number']}  |  {state}  |  words: {', '.join(t.get('words') or [])}")
            if t.get("audio"):
                print(f"  audio: {t['audio']}")
            if t["recorded"]:
                yt = t.get("youtube") or {}
                print(f"  youtube: {yt.get('url') or yt.get('status')}")
        if st["pending_uploads"]:
            print(f"Pending uploads: {', '.join(st['pending_uploads'])}")
        return 0
    if args.pron_command == "history":
        rows = pronounce_session.history_rows(ctx, limit=args.limit)
        if args.json:
            _print(rows)
            return 0
        if not rows:
            print("No pronunciation sessions yet.")
        for r in rows:
            mark = "✓" if r["recorded"] else "✗"
            print(f"{mark} {r['date']}  Day {r['day']}  youtube: {r['youtube']}  words: {', '.join(r['words'])}")
            print(f"     {r['paragraph']}")
        return 0
    if args.pron_command == "words":
        from fdecoach.config import save_config
        pron = ctx.cfg.setdefault("pronunciation", {})
        if args.add:
            words = [w.strip().lower() for w in args.add if w.strip()]
            user = json.loads(ctx.paths.config.read_text(encoding="utf-8")) if ctx.paths.config.exists() else {}
            have = [w.lower() for w in user.get("pronunciation", {}).get("words", [])]
            user.setdefault("pronunciation", {})["words"] = have + [w for w in words if w not in have]
            save_config(ctx.paths, user)
            print(f"Added: {', '.join(words)}")
        if args.remove:
            user = json.loads(ctx.paths.config.read_text(encoding="utf-8")) if ctx.paths.config.exists() else {}
            gone = [w.strip().lower() for w in args.remove]
            pron_list = user.get("pronunciation", {}).get("words", [])
            user.setdefault("pronunciation", {})["words"] = [w for w in pron_list if w.lower() not in gone]
            save_config(ctx.paths, user)
            print(f"Removed: {', '.join(gone)}")
        st = pronounce_session.status(ctx)
        print("Words:", ", ".join(st["all_words"]) or "(none yet — add with: fde-coach pronounce words --add WORD)")
        print("Due today:", ", ".join(st["due_words"]) or "-")
        return 0
    if args.pron_command == "upload":
        for line in pronounce_session.upload_pending(ctx, interactive=True):
            print(line)
        return 0
    return 2


def _parse_date(value: str):
    from fdecoach.state import today
    import datetime as dt
    if not value or value == "today":
        return today()
    if value == "tomorrow":
        return today() + dt.timedelta(days=1)
    return dt.date.fromisoformat(value)


def cmd_factory(args) -> int:
    from fdecoach import factory, factory_session as FS, macos
    ctx = _ctx(args)
    sub = args.factory_command
    if sub == "take":
        if args.detach:
            from fdecoach import app
            app.spawn_detached(["factory", "take"])
            print("Software Factory take started in the background: voice recording + slide show "
                  "(about 3 minutes). Check progress with: fde-coach factory status")
            return 0
        res = FS.run_takes(ctx)
        _print(res)
        return 0 if res.get("ok") else 1
    if sub == "prep":
        kit = FS.prepare(ctx, _parse_date(args.date), rebuild=args.rebuild)
        if args.open:
            macos.open_path(Path(kit["prep_html"]))
            macos.powerpoint_open(Path(kit["deck"]), ctx.cfg.get("presentation_app"))
        _print({k: kit[k] for k in ("date", "day", "title", "deck", "prep_html", "prep_md", "dir")})
        return 0
    if sub == "brief":
        date = _parse_date(args.date or "tomorrow")
        n = factory.day_for(FS.fhistory(ctx.paths), ctx.cfg, date, _parse_date("today"))
        d = factory.topic(n, ctx.paths) if n else None
        if d is None:
            print(f"No video planned for {date.isoformat()} (series starts {factory.start_date(ctx.cfg)}, "
                  f"{factory.total_days()} days).")
            return 1
        files = FS.write_brief(ctx, date, d)
        print(files["markdown"])
        print(f"(saved: {files['html']})", file=sys.stderr)
        if args.open:
            macos.open_path(Path(files["html"]))
        return 0
    if sub == "publish":
        res = FS.publish(ctx, _parse_date(args.date), take=args.take)
        _print(res)
        return 0 if res.get("ok") else 1
    if sub == "published":
        s = FS.mark_published(ctx, _parse_date(args.date), args.url)
        print(f"Day {s['day']} marked published: {args.url}")
        return 0
    if sub == "status":
        st = FS.status(ctx)
        if args.json:
            _print(st)
            return 0
        s = st["streak"]
        print(f"Software Factory: {st['published']}/{st['path_days']} published  |  streak {s['current']} "
              f"(best {s['best']})  |  starts {st['start_date']}  |  publish via {st['publish_mode']}")
        t = st["today"]
        if t:
            state = "PUBLISHED" if t["published"] else f"{t['takes']}/{t['max_takes']} takes"
            extra = "  (carried over)" if t["carried_over"] else ""
            print(f"Today: Day {t['day']} · {t['title']}  |  {state}{extra}")
            if t.get("prep"):
                print(f"  prep : {t['prep']}")
            if t.get("video"):
                print(f"  video: {t['video']}")
            yt = t.get("youtube") or {}
            if yt.get("url") or yt.get("status") not in (None, "none"):
                print(f"  youtube: {yt.get('url') or yt.get('status')}")
        elif st["today_topic"]:
            print(f"Today: Day {st['today_topic']['day']} · {st['today_topic']['title']} "
                  f"(kit is built at {st['prep_time']}, or now with: fde-coach factory prep)")
        if st["tomorrow_topic"]:
            print(f"Tomorrow: Day {st['tomorrow_topic']['day']} · {st['tomorrow_topic']['title']} "
                  f"(brief at {st['brief_time']})")
        return 0
    if sub == "plan":
        if args.markdown:
            text = FS.learning_path_markdown(ctx)
            if args.write:
                Path(args.write).expanduser().write_text(text, encoding="utf-8")
                print(f"Wrote {args.write}")
            else:
                print(text)
            return 0
        rows = FS.plan_rows(ctx)
        if args.json:
            _print(rows)
            return 0
        marks = {"published": "\u2713", "today": "\u25b6", "planned": " "}
        for r in rows:
            print(f"{marks[r['status']]} Day {r['day']:>2}  {r['date']:<10}  {r['title']}"
                  + (f"  {r['url']}" if r.get("url") else ""))
        return 0
    if sub == "history":
        rows = FS.history_rows(ctx, limit=args.limit)
        if args.json:
            _print(rows)
            return 0
        if not rows:
            print("No Software Factory videos yet.")
        for r in rows:
            mark = "\u2713" if r["published"] else "\u2717"
            print(f"{mark} {r['date']}  Day {r['day']}  {r['title']}  takes: {r['takes']}  "
                  f"final: {r['final_take'] or '-'}  youtube: {r['youtube']}")
        return 0
    if sub == "music":
        for kind in ("intro", "outro"):
            src = getattr(args, kind)
            if src:
                print(f"{kind}: {FS.copy_music(ctx, Path(src).expanduser(), kind)}")
        if args.regenerate:
            FS.remove_generated_music(ctx)
        for kind, where in FS.music_report(ctx).items():
            print(f"{kind}: {where}")
        return 0
    if sub == "calendar-sync":
        for line in FS.calendar_sync(ctx, clear=args.clear):
            print(line)
        return 0
    return 2


