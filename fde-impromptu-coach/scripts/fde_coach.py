def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="fde-coach", description=f"{APP_NAME} {__version__} ({SKILL_DIR})")
    p.add_argument("-v", "--verbose", action="store_true")
    sub = p.add_subparsers(dest="command", required=True)

    s = sub.add_parser("setup", help="create data folders, launcher and launchd schedule")
    s.add_argument("--time", help="daily run time HH:MM (default 05:30)")
    s.add_argument("--no-agents", action="store_true")
    s.add_argument("--no-warmup", action="store_true")
    s.set_defaults(func=cmd_setup)

    sub.add_parser("daily", help="scheduled run: build deck, open it, notify, ask to start").set_defaults(func=cmd_daily)

    s = sub.add_parser("session", help="record today's session now (QuickTime + slide show)")
    s.add_argument("--force", action="store_true", help="record again even if today is already recorded")
    s.add_argument("--detach", action="store_true", help="run in the background and return immediately")
    s.set_defaults(func=cmd_session)

    sub.add_parser("remind", help="reminder tick (launchd runs it every 15 minutes)").set_defaults(func=cmd_remind)

    s = sub.add_parser("generate", help="build today's questions + deck (keeps an existing one unless --replace)")
    s.add_argument("--source", choices=["auto", "claude", "bank"])
    s.add_argument("--replace", action="store_true", help="new questions for today (only before recording)")
    s.add_argument("--brief", help="extra guidance for Claude, e.g. 'healthcare customer, CISO audience'")
    s.add_argument("--open", action="store_true", help="open the deck afterwards")
    s.add_argument("--reveal", action="store_true", help="print the question texts (spoils the surprise)")
    s.set_defaults(func=cmd_generate)

    sub.add_parser("plan", help="JSON plan for authoring today's questions by hand").set_defaults(func=cmd_plan)

    s = sub.add_parser("build", help="build today's deck from a questions JSON file")
    s.add_argument("--questions", required=True)
    s.add_argument("--replace", action="store_true")
    s.set_defaults(func=cmd_build)

    sub.add_parser("open", help="open today's deck in PowerPoint").set_defaults(func=cmd_open)

    s = sub.add_parser("status", help="streak, today's state, uploads, schedule")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_status)

    s = sub.add_parser("history", help="past sessions and their questions")
    s.add_argument("--limit", type=int, default=14)
    s.add_argument("--reveal", action="store_true", help="also show today's questions before recording")
    s.add_argument("--json", action="store_true")
    s.set_defaults(func=cmd_history)

    s = sub.add_parser("complete", help="mark today as recorded when you recorded outside the automation")
    s.add_argument("--video", help="video path (default: newest video from today in the recordings folder)")
    s.add_argument("--no-video", action="store_true", help="you practised but have no usable video")
    s.add_argument("--note")
    s.set_defaults(func=cmd_complete)

    sub.add_parser("upload", help="upload pending recordings to YouTube (private)").set_defaults(func=cmd_upload)
    sub.add_parser("youtube-auth", help="connect YouTube once (opens a browser)").set_defaults(func=cmd_youtube_auth)
    sub.add_parser("calendar-auth", help="connect Google Calendar once for missed-practice alerts (opens a browser)"
                   ).set_defaults(func=cmd_calendar_auth)
    s = sub.add_parser("calendar-sync", help="bring the Google Calendar missed-practice alerts up to date")
    s.add_argument("--clear", action="store_true", help="delete all upcoming alerts created by this tool")
    s.set_defaults(func=cmd_calendar_sync)

    s = sub.add_parser("doctor", help="check installation, permissions and recent errors")
    s.add_argument("--warmup", action="store_true", help="trigger every macOS permission prompt now")
    s.set_defaults(func=cmd_doctor)

    sub.add_parser("install-agents", help="(re)install the launchd schedule").set_defaults(func=cmd_install_agents)
    sub.add_parser("uninstall-agents", help="remove the launchd schedule").set_defaults(func=cmd_uninstall_agents)

    s = sub.add_parser("config", help="show or change settings")
    s.add_argument("--set", action="append", metavar="KEY=VALUE",
                   help="e.g. daily_time=06:00  reminders.snooze_minutes=30  youtube.enabled=false")
    s.set_defaults(func=cmd_config)

    s = sub.add_parser("level", help="show or nudge the difficulty level")
    g = s.add_mutually_exclusive_group()
    g.add_argument("--up", action="store_true")
    g.add_argument("--down", action="store_true")
    g.add_argument("--reset", action="store_true")
    s.set_defaults(func=cmd_level)

    s = sub.add_parser("pronounce", help="daily pronunciation practice (pen method)")
    psub = s.add_subparsers(dest="pron_command", required=True)
    ps = psub.add_parser("session", help="record today's pronunciation session (audio only)")
    ps.add_argument("--force", action="store_true")
    ps.add_argument("--detach", action="store_true")
    ps.set_defaults(func=cmd_pronounce)
    psub.add_parser("daily", help="scheduled run: build the deck, notify, ask to start").set_defaults(func=cmd_pronounce)
    pg = psub.add_parser("generate", help="build today's paragraph + deck")
    pg.add_argument("--replace", action="store_true")
    pg.set_defaults(func=cmd_pronounce)
    pst = psub.add_parser("status", help="pronunciation streak, today's state, words")
    pst.add_argument("--json", action="store_true")
    pst.set_defaults(func=cmd_pronounce)
    ph = psub.add_parser("history", help="past pronunciation sessions")
    ph.add_argument("--limit", type=int, default=14)
    ph.add_argument("--json", action="store_true")
    ph.set_defaults(func=cmd_pronounce)
    pw = psub.add_parser("words", help="manage the hard-word pool")
    pw.add_argument("--add", action="append", metavar="WORD")
    pw.add_argument("--remove", action="append", metavar="WORD")
    pw.set_defaults(func=cmd_pronounce)
    psub.add_parser("upload", help="assemble + upload pending pronunciation videos").set_defaults(func=cmd_pronounce)

    s = sub.add_parser("factory", help="Software Factory daily video series (brief, kit, takes, publish)")
    fsub = s.add_subparsers(dest="factory_command", required=True)
    fs = fsub.add_parser("take", help="record today's next take (voice + slides, max 3), then publish")
    fs.add_argument("--detach", action="store_true")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("prep", help="build the recording kit: slides, prep sheet, outline, checks")
    fs.add_argument("--date", default="today", help="today (default), tomorrow or YYYY-MM-DD")
    fs.add_argument("--rebuild", action="store_true", help="re-render after editing an override")
    fs.add_argument("--open", action="store_true", help="open the prep sheet and the deck")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("brief", help="the day-before brief (default: tomorrow's video)")
    fs.add_argument("--date", help="today, tomorrow (default) or YYYY-MM-DD")
    fs.add_argument("--open", action="store_true")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("publish", help="assemble the final video from a take and publish it")
    fs.add_argument("--take", type=int, help="take number (default: the latest)")
    fs.add_argument("--date", default="today")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("published", help="record the YouTube link once the video is live")
    fs.add_argument("--url", required=True)
    fs.add_argument("--date", default="today")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("status", help="today's topic, takes, publish state and streak")
    fs.add_argument("--json", action="store_true")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("plan", help="the learning path with dates and progress")
    fs.add_argument("--json", action="store_true")
    fs.add_argument("--markdown", action="store_true", help="print the learning path document")
    fs.add_argument("--write", help="with --markdown: write it to this file")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("history", help="past videos")
    fs.add_argument("--limit", type=int, default=14)
    fs.add_argument("--json", action="store_true")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("music", help="show or set the intro/outro music")
    fs.add_argument("--intro", help="audio file to use under the intro card")
    fs.add_argument("--outro", help="audio file to use under the outro card")
    fs.add_argument("--regenerate", action="store_true", help="rebuild the generated default chords")
    fs.set_defaults(func=cmd_factory)
    fs = fsub.add_parser("calendar-sync", help="bring the brief and not-published calendar events up to date")
    fs.add_argument("--clear", action="store_true")
    fs.set_defaults(func=cmd_factory)
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return int(args.func(args) or 0)
    except KeyboardInterrupt:
        return 130
    except Exception as exc:  # noqa: BLE001 - log it and show a readable message
        import logging
        logging.getLogger("fdecoach").exception("command %s failed", args.command)
        print(f"error: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
