def cmd_status(args) -> int:
    from fdecoach import app
    st = app.status(_ctx(args))
    if args.json:
        _print(st)
        return 0
    s = st["streak"]
    print(f"Streak: {s['current']} day(s)  |  best {s['best']}  |  total sessions {s['total']}  |  level {st['level']}/5")
    pron = st.get("pronunciation")
    if pron:
        ps = pron["streak"]
        print(f"Pronunciation: {ps['current']} day(s)  |  best {ps['best']}  |  total {ps['total']}  |  "
              f"due words: {', '.join(pron['due_words']) or '-'}")
    leg = st.get("legato")
    if leg:
        ls = leg["streak"]
        state = "off" if not leg.get("enabled", True) else (
            "recorded today" if (leg.get("today") or {}).get("recorded") else "not recorded today")
        print(f"Legato: {ls['current']} day(s)  |  best {ls['best']}  |  total {ls['total']}  |  "
              f"flow level {leg.get('next_flow_level', 1)}/3  |  {state}")
    t = st["today"]
    if not t:
        print(f"Today ({st['date']}): no deck yet")
    else:
        state = "RECORDED" if t["recorded"] else "NOT RECORDED YET"
        print(f"Today ({st['date']}): Day {t['day_number']}  |  {state}  |  questions from {t['source']}")
        print(f"  deck : {t['deck']}")
        if t.get("video"):
            print(f"  video: {t['video']}")
        if t["recorded"]:
            yt = t.get("youtube") or {}
            print(f"  youtube: {yt.get('url') or yt.get('status')}")
    if st["next_reminder"]:
        extra = f" (snoozed until {st['snooze_until']})" if st["snooze_until"] else ""
        print(f"Next reminder: {st['next_reminder']}{extra}")
    if st["pending_uploads"]:
        print(f"Pending uploads: {', '.join(st['pending_uploads'])}")
    print(f"YouTube connected: {'yes' if st['youtube_configured'] else 'no (run: fde-coach youtube-auth)'}")
    if not st["calendar_configured"]:
        print("Google Calendar alerts: not connected (run: fde-coach calendar-auth)")
    elif st["calendar_today"]:
        state = {"created": "armed - alerts fire if you don't record",
                 "deleted": "cleared - recorded"}.get(st["calendar_today"], st["calendar_today"])
        print(f"Google Calendar alert today: {state}")
    print("Scheduler: " + ", ".join(f"{k.split('.')[-1]}={'on' if v else 'OFF'}" for k, v in st["agents"].items()))
    return 0


